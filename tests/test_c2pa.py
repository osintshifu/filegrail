def test_the_hash_algorithm_may_be_inherited_from_the_claim(tmp_path: Path):
    """The specification makes `alg` optional in the assertion when the claim
    already states one, and real manifests leave it out."""
    claim = _cbor(
        {
            "alg": "sha256",
            "claim_generator_info": {"name": "Quiet Tool"},
            "actions": [{"action": "c2pa.created"}],
        }
    )
    image = tmp_path / "inherited.png"
    _png_with_binding(image, claim, alg=None)

    assert "hash binding matches" in read_c2pa_manifest(image).note


def test_a_manifest_that_is_not_decodable_cbor_does_not_end_the_scan(tmp_path: Path):
    """One crafted file must not take the run down with it.

    `_walk` catches the decoder's own error and carries on, which is what makes
    a malformed manifest ordinary here rather than fatal. An exception of any
    other type walks straight past that clause, out of `read_c2pa_manifest` and
    out of the scan - a hundred-byte file denying the whole tool.
    """
    image = tmp_path / "crafted.png"
    _png_with(image, _manifest(b"\x5f\x00\xff"))

    assert read_c2pa_manifest(image) is None


def _store(*manifests: bytes) -> bytes:
    return _box(b"jumb", _description(b"c2pa", "c2pa") + b"".join(manifests))


def _manifest_box(urn: str, claim: bytes, assertions: tuple = ()) -> bytes:
    store = b"".join(
        _box(b"jumb", _description(b"c2as", label) + _box(b"cbor", payload))
        for label, payload in assertions
    )
    body = _description(b"c2ma", urn)
    if store:
        body += _box(b"jumb", _description(b"c2as", "c2pa.assertions") + store)
    body += _box(b"jumb", _description(b"c2cl", "c2pa.claim.v2") + _box(b"cbor", claim))
    return _box(b"jumb", body)


def test_active_manifest_lists_its_actions_and_ingredients(tmp_path: Path):
    """The last manifest in the store describes the file; the earlier one is
    the history of the ingredient it was edited from."""
    original = _manifest_box(
        "urn:uuid:1111", _cbor({"claim_generator_info": {"name": "Camera Firmware"}})
    )
    actions = _cbor(
        {
            "actions": [
                {"action": "c2pa.opened", "when": Tagged(0, "2026-08-01T10:00:00Z")},
                {"action": "c2pa.color_adjustments"},
                {"action": "c2pa.resized"},
            ]
        }
    )
    parent = _cbor(
        {
            "title": "IMG_0001.jpg",
            "format": "image/jpeg",
            "relationship": "parentOf",
            "document_id": "xmp.did:1111",
            "c2pa_manifest": {"url": "self#jumbf=/c2pa/urn:uuid:1111", "hash": b"\x00"},
        }
    )
    component = _cbor({"title": "logo.png", "relationship": "componentOf"})
    edited = _manifest_box(
        "urn:uuid:2222",
        _cbor({"claim_generator_info": {"name": "Photo Editor", "version": "9.1"}}),
        (
            ("c2pa.actions.v2", actions),
            ("c2pa.ingredient.v2", parent),
            ("c2pa.ingredient.v2__1", component),
        ),
    )
    image = tmp_path / "edited.png"
    _png_with(image, _store(original, edited))

    found = read_c2pa_manifest(image)

    assert found is not None
    assert found.tool == "Photo Editor 9.1"
    assert found.at == "2026-08-01T10:00:00Z"
    assert found.note == "derived from IMG_0001.jpg; 2 manifests; signature not verified"
    assert found.fields["actions"] == "c2pa.opened, c2pa.color_adjustments, c2pa.resized"
    assert found.fields["manifests"] == "2"
    assert found.fields["ingredients"] == "2"
    assert found.fields["Ingredient[1]:title"] == "IMG_0001.jpg"
    assert found.fields["Ingredient[1]:relationship"] == "parentOf"
    assert found.fields["Ingredient[1]:documentID"] == "xmp.did:1111"
    assert found.fields["Ingredient[1]:manifest"] == "own manifest"
    assert found.fields["Ingredient[2]:title"] == "logo.png"
    assert "Ingredient[2]:manifest" not in found.fields


# --- the other containers ---------------------------------------------------
#
# The same JUMBF, carried the way each container carries it: a TIFF tag, a RIFF
# chunk, a uuid box, an ID3 frame. Each layout is the one c2pa-rs writes.


def _tiff_with(path: Path, jumbf: bytes) -> None:
    """Tag 52545, typed UNDEFINED, in the first IFD."""
    base = 8 + 2 + 12 + 4
    path.write_bytes(
        b"MM\x00\x2a"
        + struct.pack(">I", 8)
        + struct.pack(">H", 1)
        + struct.pack(">HHII", 0xCD41, 7, len(jumbf), base)
        + struct.pack(">I", 0)
        + jumbf
    )


def _wav_with(path: Path, jumbf: bytes) -> None:
    """A `C2PA` chunk at the top level of the RIFF, after the format chunk."""
    fmt = b"fmt " + struct.pack("<I", 16) + struct.pack("<HHIIHH", 1, 1, 8000, 16000, 2, 16)
    manifest = (
        b"C2PA" + struct.pack("<I", len(jumbf)) + jumbf + (b"\x00" if len(jumbf) % 2 else b"")
    )
    body = b"WAVE" + fmt + manifest
    path.write_bytes(b"RIFF" + struct.pack("<I", len(body)) + body)


def _mp4_with(path: Path, jumbf: bytes) -> None:
    """A `uuid` box with the C2PA uuid: version and flags, a purpose, an offset, the store."""
    uuid = bytes.fromhex("d8fec3d61b0e483c92975828877ec481")
    payload = uuid + b"\x00\x00\x00\x00" + b"manifest\x00" + struct.pack(">Q", 0) + jumbf
    path.write_bytes(_box(b"ftyp", b"isom\x00\x00\x02\x00isom") + _box(b"uuid", payload))


def _mp3_with(path: Path, jumbf: bytes) -> None:
    """A GEOB frame whose object is the manifest store, in an ID3v2.4 tag."""
    mime = b"application/x-c2pa-manifest-store\x00"
    body = b"\x00" + mime + b"c2pa\x00" + b"c2pa\x00" + jumbf
    size = len(body)
    synchsafe = bytes([(size >> 21) & 0x7F, (size >> 14) & 0x7F, (size >> 7) & 0x7F, size & 0x7F])
    frame = b"GEOB" + synchsafe + b"\x00\x00" + body
    tag_size = len(frame)
    header = b"ID3\x04\x00\x00" + bytes(
        [(tag_size >> 21) & 0x7F, (tag_size >> 14) & 0x7F, (tag_size >> 7) & 0x7F, tag_size & 0x7F]
    )
    path.write_bytes(header + frame + b"\xff\xfb\x90\x00" + b"\x00" * 64)


def test_the_manifest_is_read_from_a_tiff_a_wav_an_mp4_and_an_mp3(tmp_path: Path):
    built = {
        "frame.dng": (_tiff_with, "tag 52545"),
        "take.wav": (_wav_with, "C2PA chunk"),
        "clip.mp4": (_mp4_with, "uuid box"),
        "track.mp3": (_mp3_with, "GEOB frame"),
    }
    for name, (build, where) in built.items():
        path = tmp_path / name
        build(path, _manifest(GENERATED_CLAIM))

        origin = read_c2pa_manifest(path)

        assert origin is not None, name
        assert origin.tool == "OpenAI Media Service API (gpt-image 2.0)", name
        assert origin.where == {"object": where}, name


