def _box(box_type: bytes, payload: bytes) -> bytes:
    return struct.pack(">I", len(payload) + 8) + box_type + payload


def _description(content_type: bytes, label: str) -> bytes:
    uuid = content_type + b"\x00\x11\x00\x10\x80\x00\x00\xaa\x008\x9bq"
    return _box(b"jumd", uuid + b"\x03" + label.encode() + b"\x00")


def _manifest(cbor_payload: bytes, assertions: tuple = ()) -> bytes:
    claim = _box(b"jumb", _description(b"c2cl", "c2pa.claim.v2") + _box(b"cbor", cbor_payload))
    body = _description(b"c2pa", "c2pa")
    if assertions:
        store = b"".join(
            _box(b"jumb", _description(b"c2as", label) + _box(b"cbor", payload))
            for label, payload in assertions
        )
        body += _box(b"jumb", _description(b"c2as", "c2pa.assertions") + store)
    return _box(b"jumb", body + claim)


def _cbor(value) -> bytes:
    """Encode the CBOR subset the tests need.

    Hand-written byte literals are encoded by their own length prefix, which is
    exactly the category of arithmetic a test should not be doing by hand.
    """

    def head(major: int, argument: int) -> bytes:
        if argument < 24:
            return bytes([major << 5 | argument])
        if argument < 0x100:
            return bytes([major << 5 | 24, argument])
        if argument < 0x10000:
            return bytes([major << 5 | 25]) + struct.pack(">H", argument)
        return bytes([major << 5 | 26]) + struct.pack(">I", argument)

    if isinstance(value, Tagged):
        return head(6, value.tag) + _cbor(value.value)
    if isinstance(value, Fixed):
        # Always four bytes, so patching the value cannot resize the manifest.
        return bytes([26]) + struct.pack(">I", value.value)
    if isinstance(value, bytes):
        return head(2, len(value)) + value
    if isinstance(value, str):
        raw = value.encode("utf-8")
        return head(3, len(raw)) + raw
    if isinstance(value, int):
        return head(0, value)
    if isinstance(value, list):
        return head(4, len(value)) + b"".join(_cbor(item) for item in value)
    if isinstance(value, dict):
        return head(5, len(value)) + b"".join(
            _cbor(key) + _cbor(item) for key, item in value.items()
        )
    raise TypeError(value)


class Fixed:
    """A CBOR integer pinned to one width, so a later patch cannot resize it."""

    def __init__(self, value: int) -> None:
        self.value = value


class Tagged:
    def __init__(self, tag: int, value) -> None:
        self.tag = tag
        self.value = value


IPTC = "http://cv.iptc.org/newscodes/digitalsourcetype/"

GENERATED_CLAIM = _cbor(
    {
        "claim_generator_info": {"name": "OpenAI Media Service API"},
        "actions": [
            {
                "action": "c2pa.created",
                "when": Tagged(0, "2026-07-15T00:00:00Z"),
                "softwareAgent": {"name": "gpt-image", "version": "2.0"},
                "digitalSourceType": IPTC + "trainedAlgorithmicMedia",
            }
        ],
    }
)


def _png_with(path: Path, jumbf: bytes) -> tuple[int, int]:
    def chunk(category: bytes, payload: bytes) -> bytes:
        return (
            struct.pack(">I", len(payload))
            + category
            + payload
            + struct.pack(">I", zlib.crc32(category + payload))
        )

    header = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 1, 1, 8, 6, 0, 0, 0))
    manifest_chunk = chunk(b"caBX", jumbf)
    path.write_bytes(header + manifest_chunk + chunk(b"IDAT", b"\x00") + chunk(b"IEND", b""))
    return len(header), len(manifest_chunk)


def _svg_with(path: Path, jumbf: bytes) -> None:
    """A drawing carrying the same manifest store, written the way XML can."""
    payload = base64.b64encode(jumbf).decode()
    path.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" xmlns:c2pa="http://c2pa.org/manifest">'
        f"<metadata><c2pa:manifest>{payload}</c2pa:manifest></metadata>"
        '<path d="M0 0 L1 1"/></svg>',
        encoding="utf-8",
    )


def test_reads_a_manifest_an_svg_carries_as_base64(tmp_path: Path):
    drawing = tmp_path / "mark.svg"
    _svg_with(drawing, _manifest(GENERATED_CLAIM))

    record = read_c2pa_manifest(drawing)

    assert record is not None
    assert record.where == {"object": "c2pa:manifest element"}


def test_reads_an_ai_generated_png(tmp_path: Path):
    image = tmp_path / "generated.png"
    _png_with(image, _manifest(GENERATED_CLAIM))

    origin = read_c2pa_manifest(image)

    assert origin is not None
    assert origin.source == "c2pa"
    assert origin.tool == "OpenAI Media Service API (gpt-image 2.0)"
    assert origin.at == "2026-07-15T00:00:00Z"
    assert "generated by an AI model" in origin.note
    assert origin.priority == 60
    assert origin.fields == {
        "claim_generator": "OpenAI Media Service API",
        "softwareAgent": "gpt-image 2.0",
        "digitalSourceType": IPTC + "trainedAlgorithmicMedia",
        "actions": "c2pa.created",
    }


